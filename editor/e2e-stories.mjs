// Accueil, ouverture d'un conte, prévisualisation illustrée, export Windows. node e2e-stories.mjs <dossier>
import { chromium } from 'playwright-core';
import { unzipSync } from 'fflate';
import { readFileSync } from 'node:fs';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge', args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
// Langue de l'interface (HERODIO_LANG=en pour l'anglais), sans passer par l'écran du premier démarrage.
await page.addInitScript((l) => localStorage.setItem('herodio-lang', l), process.env.HERODIO_LANG ?? 'fr');
await page.goto('http://localhost:1420');
await page.evaluate(() => indexedDB.deleteDatabase('keyval-store'));
await page.reload();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/s1-accueil.png` });
const t0 = Date.now();
await page.locator('.story-card', { hasText: 'Les trois petits cochons' }).click();
await page.locator('.welcome').waitFor({ state: 'detached', timeout: 60000 });
console.log('Conte ouvert en', Date.now() - t0, 'ms ; blocs :', await page.locator('.react-flow__node').count());
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/s2-graphe.png` });
await page.getByText('▶ Jouer mon histoire').click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/s3-jeu.png` });
await page.getByText('⏹ Arrêter').first().click();
console.log('Vérification :', (await page.locator('.btn.check').innerText()).trim());
await page.getByText('📦 Exporter mon histoire').click();
const dl = page.waitForEvent('download', { timeout: 300000 });
await page.locator('.export-actions .export-btn').click();
const d = await dl;
await d.saveAs(`${out}/cochons.aistory`);
const files = unzipSync(readFileSync(`${out}/cochons.aistory`));
const story = JSON.parse(new TextDecoder().decode(files['story.json']));
console.log('Pack :', Object.keys(files).filter((f) => f.endsWith('.wav')).length, 'sons,', Object.keys(files).filter((f) => f.endsWith('.jpg')).length, 'images, couverture :', story.cover, ', couleur :', story.color);
console.log('Erreurs :', errors.length ? errors : 'aucune');
await browser.close();
