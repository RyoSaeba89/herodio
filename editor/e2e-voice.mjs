// Voix automatique : activation, prévisualisation, prise « voix auto », export. node e2e-voice.mjs <dossier>
import { chromium } from 'playwright-core';
import { unzipSync } from 'fflate';
import { readFileSync } from 'node:fs';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge', args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://localhost:1420');
await page.evaluate(() => indexedDB.deleteDatabase('keyval-store'));
await page.reload();
await page.getByText('Ma première histoire').first().click();
await page.waitForTimeout(500);
console.log('Avertissements avant :', (await page.locator('.btn.check').innerText()).trim());
await page.locator('.voice-switch input').check();
console.log('Avertissements après :', (await page.locator('.btn.check').innerText()).trim());
await page.screenshot({ path: `${out}/v1-toggle.png` });
await page.getByText('▶ Jouer mon histoire').click();
const t0 = Date.now();
await page.locator('.play-card .eq').waitFor({ timeout: 30000 });
console.log('La voix lit la 1re scène après', Date.now() - t0, 'ms');
await page.screenshot({ path: `${out}/v2-play.png` });
await page.getByText('⏹ Arrêter').first().click();
// Prise « voix auto » transformée en vrai son
await page.locator('.react-flow__node').filter({ hasText: 'Le réveil' }).click();
await page.locator('.slot button[title^="Créer une prise"]').first().click();
await page.locator('.slot-info', { hasText: '🔊' }).first().waitFor({ timeout: 30000 });
console.log('Prise créée :', await page.locator('.slot-info').first().innerText());
await page.getByText('📦 Exporter mon histoire').click();
const dl = page.waitForEvent('download');
await page.locator('.export-actions .export-btn').click();
const d = await dl;
await d.saveAs(`${out}/voix.aistory`);
const files = unzipSync(readFileSync(`${out}/voix.aistory`));
const story = JSON.parse(new TextDecoder().decode(files['story.json']));
const slots = story.nodes.flatMap((n) => [n.audio, ...(n.options ?? []).map((o) => o.audio)].filter((x) => x !== undefined));
console.log('Sons dans le pack :', Object.keys(files).filter((f) => f.endsWith('.wav')).length, '| emplacements sans son :', slots.filter((a) => !a).length);
console.log('Erreurs :', errors.length ? errors : 'aucune');
await browser.close();
